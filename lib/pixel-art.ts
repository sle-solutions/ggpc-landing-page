// Stage light behind a featured sprite: stepped radial bands with an ordered (Bayer) dither and a floor pool.
function spotlight() {
  const W = 60, H = 50
  const g = grid(W, H)
  const bayer = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
  const tones: Cell[] = ["q", "h", "j", "."]
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const dx = (x + .5 - W / 2) / (W / 2), dy = (y + .5 - H * .52) / (H * .5)
    const level = Math.sqrt(dx * dx + dy * dy) * 3.3 + (bayer[y % 4][x % 4] / 16 - .5) * .9
    const tone = tones[Math.min(3, Math.max(0, Math.floor(level)))]
    if (tone !== ".") px(g, x, y, tone)
  }
  for (let y = 43; y < 50; y++) for (let x = 0; x < W; x++) {
    const dx = (x + .5 - W / 2) / (W * .36), dy = (y + .5 - 46.5) / 3
    if (Math.sqrt(dx * dx + dy * dy) + (bayer[y % 4][x % 4] / 16 - .5) * .5 < 1) px(g, x, y, "q")
  }
  return g
}

