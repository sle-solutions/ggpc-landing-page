const sprites = { gpu, cpu, cpuLarge, ram, motherboard, psu, ssd, rig, brief, chest, spotlight, flag }
export type SpriteName = keyof typeof sprites

export type Run = { x: number; y: number; w: number; c: string }

function runs(rows: string[][], color: (c: string) => string | null): Run[] {
  const out: Run[] = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const fill = color(row[x])
      if (!fill) { x++; continue }
      let w = 1
      while (x + w < row.length && row[x + w] === row[x]) w++
      out.push({ x, y, w, c: fill })
      x += w
    }
  })
  return out
}

// One path per colour keeps a sprite to a handful of DOM nodes.
function toPaths(list: Run[]) {
  const byColor = new Map<string, string>()
  for (const run of list) byColor.set(run.c, `${byColor.get(run.c) ?? ""}M${run.x} ${run.y}h${run.w}v1h-${run.w}z`)
  return [...byColor].map(([c, d]) => ({ c, d }))
}

const spriteCache = new Map<SpriteName, { w: number; h: number; paths: { c: string; d: string }[] }>()
export function sprite(name: SpriteName) {
  let entry = spriteCache.get(name)
  if (!entry) {
    const g = sprites[name]()
    entry = { w: g[0].length, h: g.length, paths: toPaths(runs(g, c => (c === "." ? null : palette[c as keyof typeof palette]))) }
    spriteCache.set(name, entry)
  }
  return entry
}

