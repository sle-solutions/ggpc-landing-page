type Cell = keyof typeof palette | "."
type Grid = Cell[][]

const grid = (w: number, h: number): Grid => Array.from({ length: h }, () => Array<Cell>(w).fill("."))
const px = (g: Grid, x: number, y: number, c: Cell) => { if (g[y] && x >= 0 && x < g[0].length) g[y][x] = c }
const rect = (g: Grid, x: number, y: number, w: number, h: number, c: Cell) => { for (let j = y; j < y + h; j++) for (let i = x; i < x + w; i++) px(g, i, j, c) }
const box = (g: Grid, x: number, y: number, w: number, h: number, fill: Cell, line: Cell = "k") => { rect(g, x, y, w, h, line); rect(g, x + 1, y + 1, w - 2, h - 2, fill) }
const hline = (g: Grid, x: number, y: number, w: number, c: Cell) => rect(g, x, y, w, 1, c)
const vline = (g: Grid, x: number, y: number, h: number, c: Cell) => rect(g, x, y, 1, h, c)
const stamp = (g: Grid, x: number, y: number, rows: string[]) => rows.forEach((row, j) => [...row].forEach((c, i) => { if (c !== ".") px(g, x + i, y + j, c as Cell) }))

